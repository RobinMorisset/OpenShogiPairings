# European nationality codes (ISO-3166-1 alpha-2, generous: includes Russia, the
# Caucasus, Turkey — consistent with the FESA/European shogi scene). A player's
# nationality is "non-European" for this study if it's a plausible 2-letter code
# not in here (a 3-letter junk code like "PRO", or a blank, does not qualify).
EUROPEAN = frozenset(
    "AD AL AM AT AZ BA BE BG BY CH CY CZ DE DK EE ES FI FO FR GB GE GG GI GR HR "
    "HU IE IM IS IT JE LI LT LU LV MC MD ME MK MT NL NO PL PT RO RS RU SE SI SK "
    "SM TR UA VA XK".split()
)


def _is_non_european(nat):
    return len(nat) == 2 and nat not in EUROPEAN


def _manifest_file_map(out):
    """(season, stem) -> original result filename, from the manifest."""
    m = {}
    path = Path(out) / "manifest.csv"
    if path.exists():
        with open(path, newline="") as fh:
            for row in csv.DictReader(fh):
                m[(row["season"], row["stem"])] = row["file"]
    return m


def compute_tournament_tags(out, corpus, refresh=False):
    """Per-tournament tags derived from the result files (parsed via fesa-players):
    whether it has any unrated player, and the set of non-European nationalities
    among its unrated players. Cached to tournament_tags.json so repeated analyses
    don't re-parse the corpus."""
    cache = Path(out) / "tournament_tags.json"
    if cache.exists() and not refresh:
        return json.loads(cache.read_text())

    fmap = _manifest_file_map(out)
    corpus = Path(corpus)
    tags = {}
    raw = Path(out) / "raw"
    missing = 0
    for csv_path in sorted(raw.rglob("*.csv")):
        season, stem = csv_path.parent.name, csv_path.stem
        key = "{}/{}".format(season, stem)
        fname = fmap.get((season, stem), stem + ".txt")
        rf = corpus / season / fname
        if not rf.exists():
            missing += 1
            continue
        proc = subprocess.run([str(bin_path("fesa-players")), str(rf)], capture_output=True, text=True)
        if proc.returncode != 0:
            missing += 1
            continue
        has_unrated = False
        noneu = set()
        for line in proc.stdout.splitlines()[1:]:
            nat, rated = line.rsplit(",", 1)
            if rated == "0":
                has_unrated = True
                if _is_non_european(nat):
                    noneu.add(nat)
        tags[key] = {"has_unrated": has_unrated, "unrated_noneu_nats": sorted(noneu)}
    if missing:
        eprint("warning: {} tournament(s) could not be tagged (result file missing/unparsed)".format(missing))
    cache.write_text(json.dumps(tags, indent=2) + "\n")
    return tags


def load_tournament_means(out):
    """Read every raw dump; return {tournament_key: {kind: {metric: run_mean}}}.

    The run-mean collapses each config's 1000 CRN-paired runs to one number per
    metric — the tournament is the unit of replication for cross-tournament
    aggregation.
    """
    raw = Path(out) / "raw"
    table = {}
    for csv_path in sorted(raw.rglob("*.csv")):
        key = "{}/{}".format(csv_path.parent.name, csv_path.stem)
        sums = {}   # kind -> metric -> [sum, count]
        with open(csv_path, newline="") as fh:
            reader = csv.DictReader(fh)
            for row in reader:
                kind = row["variant"]
                acc = sums.setdefault(kind, {m: [0.0, 0] for m, _, _ in METRICS})
                for m, _, _ in METRICS:
                    acc[m][0] += float(row[m])
                    acc[m][1] += 1
        means = {}
        for kind, macc in sums.items():
            means[kind] = {m: (macc[m][0] / macc[m][1] if macc[m][1] else float("nan")) for m, _, _ in METRICS}
        if means:
            table[key] = means
    return table


def paired_stats(pairs, higher_better):
    """Paired A/B stats over tournaments. `pairs` is a list of (a, b) per-tournament
    means (both configs present). Returns a dict with the mean difference (b-a),
    its 95% CI half-width, a z (normal approx), a distribution-free sign-test, and
    a mean relative difference. `higher_better` orients "favours b"."""
    diffs = [b - a for a, b in pairs]
    rels = [(b - a) / a for a, b in pairs if a not in (0.0,)]
    n = len(diffs)
    mean = statistics.fmean(diffs)
    if n >= 2:
        sd = statistics.stdev(diffs)
        se = sd / math.sqrt(n)
    else:
        sd = se = 0.0
    z = mean / se if se > 0 else 0.0
    # "favour b": improvement in the metric's good direction.
    fav = sum(1 for d in diffs if (d > 0) == higher_better and d != 0)
    unfav = sum(1 for d in diffs if (d < 0) == higher_better and d != 0)
    return {
        "n": n,
        "mean": mean,
        "ci": 1.959964 * se,
        "z": z,
        "stars": _stars(z),
        "median": statistics.median(diffs),
        "rel_mean": (statistics.fmean(rels) if rels else float("nan")),
        "fav": fav,
        "unfav": unfav,
        "sign_p": _sign_test_p(fav, unfav),
    }


def _stars(z):
    a = abs(z)
    if a >= 3.290527:
        return "***"
    if a >= 2.575829:
        return "**"
    if a >= 1.959964:
        return "*"
    return "ns"


def _sign_test_p(fav, unfav):
    """Two-sided exact binomial sign-test p-value for `fav` successes out of
    `fav+unfav` at p=0.5. All-integer until the final ratio so it stays exact for
    large n (float `2.0**n` overflows past n≈1024)."""
    n = fav + unfav
    if n == 0:
        return 1.0
    k = min(fav, unfav)
    tail = sum(math.comb(n, i) for i in range(0, k + 1)) / (2 ** n)  # int/int -> float, no overflow
    return min(1.0, 2.0 * tail)


def _intersection_pairs(table, a, b, metric):
    """(a, b) per-tournament means for every tournament that has *both* configs."""
    return [(t[a][metric], t[b][metric]) for t in table.values() if a in t and b in t]


def _fmt_delta(st, metric):
    rel = ""
    if metric in RELATIVE_METRICS and not math.isnan(st["rel_mean"]):
        rel = "  ({:+.1f}%)".format(100.0 * st["rel_mean"])
    return "n={:<4} {:+.3f} ±{:.3f} {:<3}{}  [favour {}/{}, sign p={:.1e}]".format(
        st["n"], st["mean"], st["ci"], st["stars"], rel, st["fav"], st["fav"] + st["unfav"], st["sign_p"]
    )


def _cmp(table, a, b, metric, higher):
    return paired_stats(_intersection_pairs(table, a, b, metric), higher)


def _report_metric_block(table, baseline, others, pairs):
    """Per-metric comparisons: each non-baseline kind vs the baseline (on their own
    support), then the requested among-others pairs. Every comparison is paired on
    exactly the tournaments where both configs are present (its own n)."""
    for m, higher, desc in METRICS:
        print()
        print("  Δ {}  [{}; {} is better]".format(m, desc, "higher" if higher else "lower"))
        for kind in others:
            print("    {:<6} vs {:<6}: {}".format(kind, baseline, _fmt_delta(_cmp(table, baseline, kind, m, higher), m)))
        for (a, b) in pairs:
            if a in others and b in others:
                print("    {:<6} vs {:<6}: {}".format(b, a, _fmt_delta(_cmp(table, a, b, m, higher), m)))


def phase_analyze(args):
    out = Path(args.out)
    if not (out / "raw").exists():
        eprint("no raw/ under {} — run the `run` phase first".format(out))
        return 1

    table = load_tournament_means(out)
    if not table:
        eprint("no dumps found under {}/raw".format(out))
        return 1

    # Corpus recap from the manifest (if present) plus what actually loaded.
    print("MacMahon-threshold study — overall comparison")
    meta_path = out / "meta.json"
    corpus = None
    if meta_path.exists():
        meta = json.loads(meta_path.read_text())
        corpus = meta.get("corpus")
        print("  runs={runs}  seed={seed}  jitter={jitter}  corpus={corpus}".format(**meta))
        if meta.get("git_commit"):
            print("  git commit: {}".format(meta["git_commit"]))
    _print_manifest_recap(out)

    # Optional subset filter (needs the corpus to re-parse player nationalities).
    if args.filter == "unrated_noneu":
        if not corpus:
            eprint("cannot filter: meta.json has no corpus path")
            return 1
        tags = compute_tournament_tags(out, corpus, refresh=args.refresh_tags)
        kept = {k: v for k, v in table.items() if tags.get(k, {}).get("unrated_noneu_nats")}
        nat_counts = collections.Counter()
        for k in kept:
            for nat in tags[k]["unrated_noneu_nats"]:
                nat_counts[nat] += 1
        print()
        print("  FILTER: only tournaments with >=1 unrated player of a non-European nationality")
        print("  matched {} of {} simulated tournaments".format(len(kept), len(table)))
        print("  non-European unrated nationalities present (tournaments each):")
        print("    " + ", ".join("{}:{}".format(n, c) for n, c in nat_counts.most_common()))
        table = kept
        if not table:
            eprint("no tournaments match the filter")
            return 1

    # Discover the config kinds actually present, ordered swiss, then finer→coarser.
    kinds = sorted({k for t in table.values() for k in t}, key=kind_sort_key)
    baseline = "swiss" if "swiss" in kinds else kinds[0]
    others = [k for k in kinds if k != baseline]
    support = {k: sum(1 for t in table.values() if k in t) for k in kinds}
    common = [key for key, t in table.items() if all(k in t for k in kinds)]

    print()
    print("  configs present (tournaments each): "
          + ", ".join("{}:{}".format(k, support[k]) for k in kinds))
    print("  common support (all configs present): {} tournaments".format(len(common)))
    print("  Δ = mean over tournaments of (config − other) per-tournament run-mean;")
    print("  each comparison is paired on its own intersection (n shown); ±95% CI")
    print("  (normal approx); stars from |z|; sign p = two-sided sign test.")

    # Descriptive within-common-block mean levels (equal weight per tournament).
    if common:
        print()
        print("  mean levels on the {} common tournaments (equal weight):".format(len(common)))
        print("    {:<6}".format("config") + "".join("{:>16}".format(m) for m, _, _ in METRICS))
        for kind in kinds:
            vals = [statistics.fmean(table[k][kind][m] for k in common) for m, _, _ in METRICS]
            print("    {:<6}".format(kind) + "".join("{:>16.4f}".format(v) for v in vals))

    # All adjacent + spanning pairs among the non-baseline kinds (finer vs coarser).
    among = [(others[i], others[j]) for i in range(len(others)) for j in range(i + 1, len(others))]
    print()
    print("=" * 78)
    print("COMPARISON — each vs {}, then finer-vs-coarser among the rest".format(baseline))
    _report_metric_block(table, baseline, others, among)

    print()
    print("Notes: tournament is the unit of replication (runs within one share common")
    print("random numbers, so are not independent). Each pair is compared only on")
    print("tournaments where both configs exist — coverage grows as the group floor N")
    print("shrinks, so smaller-N configs carry larger n against the baseline.")
    return 0


def _print_manifest_recap(out):
    path = Path(out) / "manifest.csv"
    if not path.exists():
        return
    run = skipped = errors = 0
    ncfg = collections.Counter()
    with open(path, newline="") as fh:
        for row in csv.DictReader(fh):
            st = row["status"]
            if st == "run":
                run += 1
                ncfg[row["n_configs"]] += 1
            elif st == "error":
                errors += 1
            else:  # skipped_no_n<gate>
                skipped += 1
    dist = ", ".join("{}×{}cfg".format(c, n) for n, c in sorted(ncfg.items(), key=lambda x: -int(x[0] or 0)))
    print("  manifest: {} simulated ({}), {} skipped, {} errors".format(run, dist, skipped, errors))


