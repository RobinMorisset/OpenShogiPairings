def build_binaries():
    eprint("building osp-sim, mm-grades, fesa-players, cup-detect (release) ...")
    subprocess.run(
        ["cargo", "build", "--release", "--bin", "osp-sim", "--bin", "mm-grades",
         "--bin", "fesa-players", "--bin", "cup-detect"],
        cwd=REPO,
        check=True,
    )


def run_mm_grades(result_file, n, workdir):
    """Run mm-grades for one N into `workdir`; return (paths, info).

    `paths` is the list of the three generated JSON files (a, b, c) in order, or
    [] if mm-grades emitted nothing (field too small for N). `info` carries a few
    parsed facts (players, groups) for the manifest. Raises on a parse/tool
    failure so the caller can stop or record it.
    """
    workdir.mkdir(parents=True, exist_ok=True)
    proc = subprocess.run(
        [str(bin_path("mm-grades")), str(result_file), str(n), str(workdir)],
        capture_output=True,
        text=True,
    )
    if proc.returncode != 0:
        raise RuntimeError("mm-grades failed on {} (N={}):\n{}".format(result_file, n, proc.stderr.strip()))

    info = {"players": None, "groups": None}
    for line in proc.stderr.splitlines():
        # "107 players (102 rated, 5 unrated); N = 8; 8 threshold(s) -> 9 group(s):"
        if " players (" in line and "threshold(s)" in line:
            try:
                info["players"] = int(line.split(" players", 1)[0].strip())
                info["groups"] = int(line.split("-> ", 1)[1].split(" group", 1)[0])
            except (ValueError, IndexError):
                pass

    stem = result_file.stem
    expected = [workdir / "{}.mm{}-{}.json".format(stem, n, letter) for letter in MM_LETTERS]
    present = [p for p in expected if p.exists()]
    if present and len(present) != len(MM_LETTERS):
        raise RuntimeError("mm-grades produced a partial set for {} (N={}): {}".format(result_file, n, present))
    return present, info


def stage_configs(result_file, out, season, stem, ns, letters, keep_going):
    """Generate + stage all configs for one tournament under out/configs/... .

    `ns` is the ascending list of group-size floors to sweep; `letters` the mm-grades
    variants (subset of a/b/c/d). The smallest N is the *gate*: if it yields no
    thresholds the tournament is skipped entirely. Each larger N contributes its
    configs only when it too yields thresholds (a strictly bigger field is needed),
    so coverage shrinks as N grows.

    Returns (kinds, info): `kinds` is the ordered list of config-kind labels that
    were staged (always starts with "swiss"), empty when the tournament is skipped.
    On a tooling error it either raises (default) or returns info["error"]
    (keep_going).
    """
    cfg_dir = out / "configs" / season / stem
    if cfg_dir.exists():
        shutil.rmtree(cfg_dir)
    cfg_dir.mkdir(parents=True, exist_ok=True)
    work = out / "_work" / season / stem
    if work.exists():
        shutil.rmtree(work)

    info = {"players": None, "groups": {}, "skip": None, "error": None, "half_abs": False, "cup": None}
    letter_idx = {l: i for i, l in enumerate(MM_LETTERS)}
    gate = ns[0]
    kinds = []

    for i, n in enumerate(ns):
        try:
            paths, ninfo = run_mm_grades(result_file, n, work / "n{}".format(n))
        except RuntimeError as e:
            if keep_going:
                info["error"] = str(e)
                return [], info
            raise
        if i == 0:
            info["players"] = ninfo["players"]
            if not paths:
                info["skip"] = "no_n{}".format(gate)  # gate empty -> skip entirely
                return [], info
            # First real N: set up the baseline, the file's absence convention, and
            # whether it was actually run as a cup (applied to the whole run below).
            info["half_abs"] = prefers_half_point_absences(result_file)
            try:
                info["cup"] = detect_cup(result_file)
            except RuntimeError as e:
                if keep_going:
                    info["error"] = str(e)
                    return [], info
                raise
            (cfg_dir / "swiss.json").write_text("{}\n")  # default == basic Swiss
            kinds.append("swiss")
        if not paths:
            continue  # this (larger) N doesn't apply to this field
        info["groups"][n] = ninfo["groups"]
        for letter in letters:
            label = kind_name(n, letter)
            shutil.copyfile(paths[letter_idx[letter]], cfg_dir / (label + ".json"))
            kinds.append(label)

    # Apply the file's absence convention to *all* staged configs uniformly, so
    # swiss and every MacMahon variant score this tournament's absences the same.
    if info["half_abs"]:
        for kind in kinds:
            cfg_file = cfg_dir / (kind + ".json")
            cfg = json.loads(cfg_file.read_text())
            cfg["half_point_absences"] = True
            cfg_file.write_text(json.dumps(cfg, indent=2) + "\n")

    shutil.rmtree(work, ignore_errors=True)
    return kinds, info


def run_osp_sim(result_file, cfg_dir, kinds, dump_path, cup, args):
    """Invoke osp-sim for one tournament, writing the per-run dump. When `cup` is
    (size, nation), the run reproduces the hybrid direct-elimination cup, so the
    cup rounds are bracket-paired rather than Swiss — the faithful format for a
    tournament that was actually a cup. Raises on failure (osp-sim's stderr)."""
    dump_path.parent.mkdir(parents=True, exist_ok=True)
    config_files = [str(cfg_dir / (k + ".json")) for k in kinds]
    cmd = [
        str(bin_path("osp-sim")),
        "--results", str(result_file),
        "--jitter", str(args.jitter),
        "--runs", str(args.runs),
        "--seed", str(args.seed),
        "--configs", *config_files,
        "--dump-runs", str(dump_path),
    ]
    if cup:
        size, nation = cup
        cmd += ["--cup-size", str(size), "--cup-nations", nation]
    proc = subprocess.run(cmd, capture_output=True, text=True)
    if proc.returncode != 0:
        raise RuntimeError("osp-sim failed on {}:\n{}".format(result_file, proc.stderr.strip()))


def phase_run(args):
    out = Path(args.out)
    corpus = Path(args.corpus)
    out.mkdir(parents=True, exist_ok=True)
    (out / "raw").mkdir(exist_ok=True)

    if not args.no_build:
        build_binaries()
    for name in ("osp-sim", "mm-grades"):
        if not bin_path(name).exists():
            eprint("error: missing binary {} (build it first)".format(bin_path(name)))
            return 1

    ns = sorted(set(args.ns))
    letters = [l for l in MM_LETTERS if l in set(args.letters)]  # canonical a,b,c order
    expected_full = 1 + len(ns) * len(letters)  # swiss + every (N, letter)

    # Persist the run parameters for provenance / reproducibility.
    meta = {
        "corpus": str(corpus),
        "runs": args.runs,
        "seed": args.seed,
        "jitter": args.jitter,
        "ns": ns,
        "letters": letters,
        "started": time.strftime("%Y-%m-%d %H:%M:%S"),
        "git_commit": _git_commit(),
    }
    (out / "meta.json").write_text(json.dumps(meta, indent=2) + "\n")

    manifest_path = out / "manifest.csv"
    new_manifest = not manifest_path.exists() or args.force
    manifest = open(manifest_path, "w" if new_manifest else "a", newline="")
    writer = csv.writer(manifest)
    if new_manifest:
        writer.writerow(
            ["season", "file", "stem", "status", "players", "n_configs", "configs", "half_abs", "cup", "error"]
        )

    seasons = season_dirs(corpus)
    if args.seasons:
        wanted = set(args.seasons)
        seasons = [s for s in seasons if s.name in wanted]

    totals = dict(files=0, run=0, full=0, partial=0, skipped=0, cached=0, errors=0, cups=0)
    t0 = time.time()

    for season in seasons:
        files = result_files(season)
        if args.max_files:
            files = files[: args.max_files]
        s = dict(files=0, run=0, full=0, partial=0, skipped=0, cached=0, errors=0, cups=0)

        for rf in files:
            stem = rf.stem
            totals["files"] += 1
            s["files"] += 1
            dump_path = out / "raw" / season.name / (stem + ".csv")

            # Resume: a non-empty dump already there means done (unless --force).
            if dump_path.exists() and dump_path.stat().st_size > 0 and not args.force:
                totals["cached"] += 1
                s["cached"] += 1
                continue

            try:
                kinds, info = stage_configs(rf, out, season.name, stem, ns, letters, args.keep_going)
            except RuntimeError as e:
                eprint("\nERROR (config generation): {}".format(e))
                eprint("stopping (use --keep-going to record and continue).")
                manifest.close()
                return 1

            players = info["players"] or ""
            cup_str = "{}:{}".format(*info["cup"]) if info.get("cup") else ""
            if info["error"]:
                writer.writerow([season.name, rf.name, stem, "error", players, 0, "", "", cup_str, info["error"].replace("\n", " ")])
                totals["errors"] += 1
                s["errors"] += 1
                continue

            if not kinds:  # skipped (gate N yielded no thresholds)
                writer.writerow([season.name, rf.name, stem, info["skip"], players, 0, "", "", cup_str, ""])
                totals["skipped"] += 1
                s["skipped"] += 1
                continue

            try:
                run_osp_sim(rf, out / "configs" / season.name / stem, kinds, dump_path, info["cup"], args)
            except RuntimeError as e:
                if args.keep_going:
                    writer.writerow([season.name, rf.name, stem, "error", players, len(kinds), "|".join(kinds), int(info["half_abs"]), cup_str, str(e).replace("\n", " ")])
                    totals["errors"] += 1
                    s["errors"] += 1
                    continue
                eprint("\nERROR (osp-sim): {}".format(e))
                eprint("stopping (use --keep-going to record and continue).")
                manifest.close()
                return 1

            writer.writerow([
                season.name, rf.name, stem, "run", players, len(kinds), "|".join(kinds), int(info["half_abs"]), cup_str, "",
            ])
            totals["run"] += 1
            s["run"] += 1
            if cup_str:
                totals["cups"] += 1
                s["cups"] += 1
            full = len(kinds) == expected_full
            key = "full" if full else "partial"
            totals[key] += 1
            s[key] += 1
            manifest.flush()

        eprint(
            "[{season}] {files} files -> {run} run ({full} full, {partial} partial), "
            "{skipped} skipped, {cached} cached{cup}{err}".format(
                season=season.name, files=s["files"], run=s["run"], full=s["full"],
                partial=s["partial"], skipped=s["skipped"], cached=s["cached"],
                cup="" if not s["cups"] else ", {} cup".format(s["cups"]),
                err="" if not s["errors"] else ", {} ERRORS".format(s["errors"]),
            )
        )

    manifest.close()
    dt = time.time() - t0
    eprint("\n=== run complete in {:.0f}s ===".format(dt))
    eprint("sweep             : Ns={} letters={} (full = {} configs)".format(ns, letters, expected_full))
    eprint("files seen        : {}".format(totals["files"]))
    eprint("simulated         : {}  ({} full, {} partial)".format(totals["run"], totals["full"], totals["partial"]))
    eprint("skipped (gate N)  : {}".format(totals["skipped"]))
    eprint("cached (resumed)  : {}".format(totals["cached"]))
    eprint("cups detected     : {}  (run as hybrid direct-elimination cups)".format(totals["cups"]))
    eprint("errors            : {}".format(totals["errors"]))
    eprint("raw dumps + manifest under {}".format(out))
    return 0


def _git_commit():
    try:
        return subprocess.run(
            ["git", "rev-parse", "HEAD"], cwd=REPO, capture_output=True, text=True
        ).stdout.strip()
    except Exception:
        return None


