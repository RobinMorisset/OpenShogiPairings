REPO = Path(__file__).resolve().parent.parent
DEFAULT_CORPUS = REPO / "test_files" / "fesa_results"
DEFAULT_OUT = REPO / "study_out"
INVALID_DIRNAME = "invalid"

# Config kinds are named `swiss` and `n<N><letter>` (e.g. `n10a`), where N is the
# mm-grades group-size floor and the letter is its variant. Which N values and
# letters to sweep is chosen per run (--ns / --letters); the baseline swiss is
# always included. mm-grades emits every variant, in this letter order.
MM_LETTERS = ["a", "b", "c", "d"]


def kind_name(n, letter):
    return "n{}{}".format(n, letter)


def kind_sort_key(kind):
    """Order kinds as: swiss first, then by N ascending (finer groups first), then
    by variant letter."""
    if kind == "swiss":
        return (0, 0, "")
    m = re.match(r"n(\d+)([a-z])$", kind)
    return (1, int(m.group(1)), m.group(2)) if m else (2, 0, kind)

# The dump columns (osp-sim --dump-runs), and which are "higher is better".
METRICS = [
    ("mean_diff", False, "mean|d| (ELO gap between paired opponents)"),
    ("frac_exceed", False, "P(|d|>400)"),
    ("fidelity", True, "standings fidelity (Spearman vs true strength)"),
    ("hit", True, "top-1 hit rate (winner is the truly-strongest player)"),
    ("interest", True, "interest(W) (game-interest welfare)"),
]
# mean_diff / frac_exceed also get a relative-Δ%, since their scale varies a lot
# across fields.
RELATIVE_METRICS = {"mean_diff", "frac_exceed"}


# ----------------------------------------------------------------------------
# Small helpers
# ----------------------------------------------------------------------------

def eprint(*a, **k):
    print(*a, file=sys.stderr, **k)
    sys.stderr.flush()


def bin_path(name):
    p = REPO / "target" / "release" / name
    return p


def season_dirs(corpus):
    """Every season subdirectory (sorted), excluding the invalid/ bucket."""
    out = []
    for entry in sorted(corpus.iterdir()):
        if entry.is_dir() and entry.name != INVALID_DIRNAME:
            out.append(entry)
    return out


def result_files(season):
    """The result files in a season dir (sorted), ignoring dotfiles/archives."""
    out = []
    for entry in sorted(season.iterdir()):
        if entry.is_file() and not entry.name.startswith(".") and entry.suffix != ".gz":
            out.append(entry)
    return out


# A round cell for an absent player is the opponent number `0` with a result
# sign: `0=` (scored a half point) or `0-` (scored nothing). These must be matched
# as whole tokens — a naive substring would count the `0=` inside `10=` (a draw
# against player 10). `(?<!\S)` anchors to a token start (after whitespace / line
# start), tolerating a trailing `(annotation)`; the negative digit-lookbehind on
# the `0` is redundant with that but harmless.
_ABSENT_HALF = re.compile(r"(?<!\S)0=")
_ABSENT_ZERO = re.compile(r"(?<!\S)0-")


def prefers_half_point_absences(result_file):
    """True when the file has strictly more half-point absences (`0=`) than
    zero-point ones (`0-`), i.e. its convention is that an absence scores ½. FESA
    tables are Latin-1; a byte value equals its code point, matching osp-core's
    decode_latin1."""
    text = result_file.read_text(encoding="latin-1")
    return len(_ABSENT_HALF.findall(text)) > len(_ABSENT_ZERO.findall(text))


def detect_cup(result_file):
    """(size, nation) when the file was run as a single-elimination cup among the
    top 2^N players of its most common nationality, else None. Delegates to
    cup-detect, which reuses osp-core's cup seeding + bracket replay, so a hit is a
    tournament osp-sim can reproduce as that hybrid cup. Raises on a tool failure."""
    proc = subprocess.run(
        [str(bin_path("cup-detect")), str(result_file)], capture_output=True, text=True
    )
    if proc.returncode != 0:
        raise RuntimeError("cup-detect failed on {}:\n{}".format(result_file, proc.stderr.strip()))
    out = proc.stdout.strip()
    if not out:
        return None
    size, nation = out.split(",", 1)
    return int(size), nation


