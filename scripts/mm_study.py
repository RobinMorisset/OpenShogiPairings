#!/usr/bin/env python3
"""mm_study.py — drive a large-scale MacMahon-threshold study over a FESA corpus.

It compares a baseline Swiss config against MacMahon configs generated by
mm-grades at one or more group-size floors N and variants a/b/c:

    swiss                     basic Swiss (default settings, no MacMahon)
    n<N>a                     mm-grades thresholds only (static MacMahon)
    n<N>b                     + estimate-MM with a Flat unrated prior
    n<N>c                     + estimate-MM with the asymmetric Huber-Laplace prior

(mm-grades picks thresholds on grade boundaries so every group holds at least N
players.) Which Ns and letters to sweep is chosen per run via --ns / --letters;
the default `--ns 10 20 --letters a b c` is the original seven-config study.

The smallest N is the *gate*: a tournament whose field is too small for it is
skipped entirely. Larger Ns need progressively bigger fields, so each contributes
its configs only to the tournaments large enough — coverage shrinks as N grows,
and the config sets nest.

The study runs in two phases so the (expensive) simulation is never repeated
just to re-analyse:

    run      simulate every tournament, storing per-run dumps + a manifest;
    analyze  read the stored dumps and print one overall comparison.

Only `analyze` produces a report — there are no per-tournament reports. Every
metric comparison is *paired within a tournament* (the configs share common
random numbers per run) and then aggregated *across tournaments* (the independent
unit of replication). Each pair of configs is compared only on the tournaments
where both were run (its own n), so no two configs are ever compared over
different tournament sets. `analyze --filter unrated_noneu` restricts to
tournaments with an unrated player of a non-European nationality.

Usage:
    scripts/mm_study.py run     [--ns N... --letters a b c] [options]
    scripts/mm_study.py analyze [--out DIR] [--filter unrated_noneu]

Run `scripts/mm_study.py run -h` for the knobs (runs, seed, jitter, corpus,
season/file filters, --keep-going, --force, --no-build).
"""

